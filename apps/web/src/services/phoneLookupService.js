/**
 * Searches the master ledger by phone number and returns
 * the matched name, email, and source found.
 *
 * @param {string} phoneNumber - The phone number to search (e.g., "+249960452223")
 * @returns {Object} - Matched contact details or not found status
 */
export function lookupByPhoneNumber(phoneNumber) {
    if (!phoneNumber || !phoneNumber.trim()) {
        return { found: false, message: 'Phone number query cannot be empty.' };
    }

    // Clean formatting (remove spaces, parentheses, dashes)
    const cleanQuery = phoneNumber.trim().replace(/[\s\-\(\)]/g, '');

    const matched = MASTER_LEDGER_CONTACTS.find((contact) => {
        if (!contact.phone) return false;
        const cleanContactPhone = contact.phone.replace(/[\s\-\(\)]/g, '');
        return cleanContactPhone.includes(cleanQuery) || cleanQuery.includes(cleanContactPhone);
    });

    if (matched) {
        return {
            found: true,
            gaId: matched.id,
            name: matched.name,
            email: matched.email || 'Not Provided / Masked',
            phone: matched.phone,
            university: matched.univ,
            sourceFound: matched.sourceFound
        };
    }

    return {
        found: false,
        query: phoneNumber,
        message: 'No matching record found for this phone number in the local Independent Ledger.'
    };
}

/**
 * Searches the master ledger by GA-ID
 *
 * @param {string} gaId - The GA ID to search (e.g., "GA087" or "GA-087")
 * @returns {Object}
 */
export function lookupContactByGaId(gaId) {
    if (!gaId || !gaId.trim()) return { found: false };
    const clean = gaId.trim().toUpperCase().replace(/[^A-Z0-9]/g, '');

    const matched = MASTER_LEDGER_CONTACTS.find((c) => {
        const cId = (c.id || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
        return cId === clean;
    });

    if (matched) {
        return {
            found: true,
            contact: matched
        };
    }

    return { found: false };
}

