function getFacultyById(id) {
  return SUDANESE_MEDICAL_FACULTIES.find(f => f.id === id || f.code === id);
}

function filterFaculties(category, query) {
  let list = SUDANESE_MEDICAL_FACULTIES;
  if (category && category !== 'ALL') {
    list = list.filter(f => f.type === category);
  }
  if (query && query.trim() !== '') {
    const q = query.trim().toLowerCase();
    list = list.filter(f => 
      f.nameAr.toLowerCase().includes(q) ||
      f.nameEn.toLowerCase().includes(q) ||
      f.shortName.toLowerCase().includes(q) ||
      f.city.toLowerCase().includes(q) ||
      f.state.toLowerCase().includes(q) ||
      f.code.toLowerCase().includes(q)
    );
  }
  return list;
}
